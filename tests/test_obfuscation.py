"""RFC 8907 sec. 4.5 body obfuscation.

The pad vector is self-generated by tests/vectors/make_obfuscation_vector.py, which does not
import tacacs. It is not a vendor capture; no packet vector exists in the RFC.
"""

from __future__ import annotations

import hashlib

import pytest

from tacacs.header import Header, PacketType
from tacacs.obfuscation import ObfuscationError, deobfuscate, obfuscate, pseudo_pad

KEY = b"tac_plus_key"
PAD_40 = bytes.fromhex(
    "5af8c3f571bbe9433d5be28903bafe5a42cbcdb081d2a270cf0e2e8545357c7beb2b1c768f4e667c"
)


def hdr(flags=0, seq_no=1, session_id=0x0BADCAFE):
    return Header(0xC, 0, PacketType.AUTHEN, seq_no, flags, session_id, 0)


def test_pad_vector():
    assert pseudo_pad(0x0BADCAFE, KEY, 0xC0, 1, 40) == PAD_40


def test_obfuscate_uses_the_pad_vector():
    body = bytes(range(40))
    assert obfuscate(body, hdr(), KEY) == bytes(a ^ b for a, b in zip(body, PAD_40, strict=True))


@pytest.mark.parametrize("size", [0, 1, 15, 16, 17, 32, 33, 65535])
def test_xor_is_involutive(size):
    body = bytes(i % 251 for i in range(size))
    assert deobfuscate(obfuscate(body, hdr(), KEY), hdr(), KEY) == body


def test_length_zero_body_returns_empty():
    assert obfuscate(b"", hdr(), KEY) == b""


def test_wrong_key_does_not_round_trip():
    body = b"secret body of some length"
    assert deobfuscate(obfuscate(body, hdr(), KEY), hdr(), b"other") != body


def test_different_seq_gives_different_pad():
    assert pseudo_pad(1, KEY, 0xC0, 1, 16) != pseudo_pad(1, KEY, 0xC0, 3, 16)


def test_refuses_when_unencrypted_flag_set():
    with pytest.raises(ObfuscationError):
        obfuscate(b"x", hdr(flags=1), KEY)
    with pytest.raises(ObfuscationError):
        deobfuscate(b"x", hdr(flags=1), KEY)


def test_refuses_empty_key():
    with pytest.raises(ObfuscationError):
        obfuscate(b"x", hdr(), b"")
    with pytest.raises(ObfuscationError):
        pseudo_pad(1, b"", 0xC0, 1, 1)


def test_chain_uses_previous_hash_not_counter():
    pad = pseudo_pad(0x0BADCAFE, KEY, 0xC0, 1, 32)
    prefix = bytes.fromhex("0badcafe") + KEY + bytes([0xC0, 1])
    first = hashlib.md5(prefix, usedforsecurity=False).digest()
    assert pad[:16] == first
    assert pad[16:] == hashlib.md5(prefix + first, usedforsecurity=False).digest()


def test_length_over_65536_refused_before_hashing():
    with pytest.raises(ObfuscationError):
        pseudo_pad(1, KEY, 0xC0, 1, 2**32 - 1)
